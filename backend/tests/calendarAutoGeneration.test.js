const test = require('node:test');
const assert = require('node:assert/strict');

const geminiPath = require.resolve('../services/geminiAI');
require.cache[geminiPath] = { id: geminiPath, filename: geminiPath, loaded: true, exports: {} };
const { processAutoGeneration, remapProposalItems } = require('../services/contentCalendarService');
const { makeCooldown } = require('../services/routeCooldown');

// A tiny in-memory stand-in that understands exactly the update shapes processAutoGeneration uses.
function fakeModel(calendars) {
  const find = (id) => calendars.find((c) => String(c._id) === String(id));
  const itemOf = (c, weekId, itemId) => c.weeks.find((w) => String(w._id) === String(weekId)).items.find((i) => String(i._id) === String(itemId));
  return {
    calendars,
    find: () => ({ limit: async () => calendars.filter((c) => c.autoGenerate && c.approved) }),
    updateOne: async (filter, update, opts = {}) => {
      const c = find(filter._id);
      if (!c) return { modifiedCount: 0 };
      if (filter.autoGeneratedCount && c.autoGeneratedCount >= filter.autoGeneratedCount.$lt) return { modifiedCount: 0 };
      const af = opts.arrayFilters || [];
      const weekId = af[0] && af[0]['w._id'];
      const itemId = af[1] && af[1]['i._id'];
      const it = itemOf(c, weekId, itemId);
      const want = filter.weeks && filter.weeks.$elemMatch.items.$elemMatch.status;
      if (want && !want.$in.includes(it.status)) return { modifiedCount: 0 };
      const need = af[1] && af[1]['i.status'];
      if (need && it.status !== need) return { modifiedCount: 0 };
      for (const [k, v] of Object.entries(update.$set || {})) {
        if (k.startsWith('weeks.$[w].items.$[i].')) it[k.split('.').pop()] = v; else c[k] = v;
      }
      for (const [k, v] of Object.entries(update.$inc || {})) c[k] = (c[k] || 0) + v;
      return { modifiedCount: 1 };
    }
  };
}
const mk = (status, extra = {}) => ({ _id: 'cal1', userId: 'u1', autoGenerate: true, approved: true, autoGeneratedCount: 0, autoGenerateLimit: 7,
  weeks: [{ _id: 'w1', weekNumber: 1, items: [{ _id: 'i1', day: new Date().getDate(), status, headline: 'h' }] }], ...extra });
const guard = (ok = true) => ({ calls: [], recorded: [], check: async function (a) { this.calls.push(a); return { ok }; }, record: async function (a, n) { this.recorded.push([a, n]); } });
const run = (model, g, generate, now) => processAutoGeneration({ now, deps: { ContentCalendar: model, spendGuard: g, generate, blockedIds: async () => [] } });

test('rows already generated or generating are never made again', async () => {
  for (const s of ['generated', 'generating']) {
    const model = fakeModel([mk(s)]); let n = 0;
    await run(model, guard(), async () => { n += 1; });
    assert.equal(n, 0, s);
  }
});

test('a made row is marked generated and counted once with the spend recorded', async () => {
  const model = fakeModel([mk('approved')]); const g = guard();
  await run(model, g, async (cal, item) => { item.generatedDraftId = 'd1'; item.status = 'generated'; return { draft: { _id: 'd1' }, campaign: { _id: 'c1' } }; });
  const row = model.calendars[0].weeks[0].items[0];
  assert.equal(row.status, 'generated');
  assert.equal(model.calendars[0].autoGeneratedCount, 1);
  assert.deepEqual(g.calls, ['image_generated']);
  assert.deepEqual(g.recorded, [['image_generated', 1]]);
});

test('overlapping runs make the row once', async () => {
  const model = fakeModel([mk('draft')]); let n = 0;
  const slow = async (cal, item) => { n += 1; await new Promise((r) => setTimeout(r, 20)); item.status = 'generated'; return {}; };
  await Promise.all([run(model, guard(), slow), run(model, guard(), slow), run(model, guard(), slow)]);
  assert.equal(n, 1);
  assert.equal(model.calendars[0].autoGeneratedCount, 1);
});

test('the monthly cap is never overshot', async () => {
  const model = fakeModel([mk('draft', { autoGeneratedCount: 7 })]); let n = 0;
  await run(model, guard(), async () => { n += 1; });
  assert.equal(n, 0);
});

test('a failure puts the row back and gives the count back, a refused spend check skips quietly', async () => {
  const model = fakeModel([mk('approved')]);
  await run(model, guard(), async () => { throw new Error('boom'); });
  assert.equal(model.calendars[0].weeks[0].items[0].status, 'approved');
  assert.equal(model.calendars[0].autoGeneratedCount, 0);
  let n = 0; const g = guard(false);
  await run(model, g, async () => { n += 1; });
  assert.equal(n, 0);
  assert.equal(model.calendars[0].weeks[0].items[0].status, 'approved');
});

test('turning auto-generation off and on no longer resets the count', () => {
  const src = require('node:fs').readFileSync(require('node:path').join(__dirname, '../routes/contentCalendar.js'), 'utf8');
  assert.doesNotMatch(src, /autoGeneratedCount\s*=\s*0/);
});

test('regenerate keeps open weekly items pointing at the new rows for the same day', async () => {
  const oldCal = { weeks: [{ items: [{ _id: 'o1', day: 3 }, { _id: 'o2', day: 9 }] }] };
  const newCal = { weeks: [{ items: [{ _id: 'n1', day: 3 }] }] };
  const proposals = [{ _id: 'p', items: [{ id: 'a', status: 'proposed', calendarItemId: 'o1' }, { id: 'b', status: 'approved', calendarItemId: 'o2' }, { id: 'c', status: 'made', calendarItemId: 'o1' }, { id: 'd', status: 'proposed', calendarItemId: null }] }];
  const saved = [];
  const model = { find: async () => proposals, updateOne: async (f, u) => { saved.push(u.$set); return {}; } };
  await remapProposalItems({ userId: 'u', oldCalendar: oldCal, newCalendar: newCal, WeeklyProposal: model });
  assert.equal(proposals[0].items[0].calendarItemId, 'n1');
  assert.equal(proposals[0].items[1].calendarItemId, 'o2');
  assert.equal(proposals[0].items[2].calendarItemId, 'o1');
  assert.equal(saved.length, 1);
});

test('the cooldown allows one call per window per account and says when', () => {
  let t = 1000; const cd = makeCooldown(10 * 60 * 1000, () => t);
  assert.equal(cd.hit('a').ok, true);
  assert.equal(cd.hit('a').ok, false);
  assert.equal(cd.hit('b').ok, true);
  t += 10 * 60 * 1000 + 1;
  assert.equal(cd.hit('a').ok, true);
});
