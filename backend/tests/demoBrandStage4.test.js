// The demo brand seed, Stage 4 (walkthrough fixes): pure parts only, no database, no network.
const test = require('node:test');
const assert = require('node:assert');
const mongoose = require('mongoose');

const K = require('../scripts/demo-brand/constants');
const content = require('../scripts/demo-brand/content');
const videos = require('../scripts/demo-brand/videos');
const extras = require('../scripts/demo-brand/extras');
const competitors = require('../scripts/demo-brand/competitors');
const inbox = require('../scripts/demo-brand/inbox');
const { istWeek } = require('../services/weekIst');

const BASE = 'http://localhost:5000';
const UID = new mongoose.Types.ObjectId();
const DAY = 86400000;
const productIds = Object.fromEntries(K.PRODUCTS.map((p) => [p.slug, new mongoose.Types.ObjectId()]));
const built = (now) => content.build({ userId: UID, now, base: BASE, productIds, videoUrls: videos.videoUrlsOf(BASE) });
const model = (n) => require(`../models/${n}`);

// every weekday of one week: the current India week always has posts before today (Home's "Posts this week")
for (const day of ['2026-10-20', '2026-10-21', '2026-10-22', '2026-10-23', '2026-10-25']) {
  test(`this week is not empty on ${day} (posted before today, in the same India week)`, () => {
    const now = new Date(`${day}T11:30:00Z`);
    const week = istWeek(now);
    const b = built(now);
    const thisWeek = b.campaigns.filter((c) => c.status === 'posted' && c.publishedAt >= week.startsAt && c.publishedAt < now);
    assert.ok(thisWeek.length >= 1, `posted this week: ${thisWeek.length}`);
    assert.ok(b.campaigns.filter((c) => c.status === 'posted' && c.publishedAt > now).length === 0, 'nothing posted in the future');
    assert.deepStrictEqual(b.summary, { needsApproval: 8, drafts: 4, approved: 4, scheduled: 10, posted: 55, archived: 6, binned: 3 });
  });
}

test('the calendar limit is never smaller than the number made, and is one of the app\'s choices', () => {
  const b = built(new Date('2026-10-21T11:30:00Z'));
  for (const c of b.calendars) { assert.ok(c.autoGenerateLimit >= c.autoGeneratedCount, c.month); assert.ok([3, 5, 7, 10, 14, 20, 30].includes(c.autoGenerateLimit)); }
});

test('archived posts are recent (the Archived view shows them on its first page)', () => {
  const b = built(new Date('2026-10-21T11:30:00Z'));
  const arch = b.drafts.filter((d) => d.status === 'archived');
  assert.strictEqual(arch.length, 6);
  assert.ok(arch.every((d) => { const age = Date.parse('2026-10-21T11:30:00Z') - d.createdAt.getTime(); return age < 3 * DAY && d.updatedAt >= d.createdAt; }));
});

test('LinkedIn has measured posts in the last 30 days, and every posted campaign carries an https link per platform', () => {
  const now = new Date('2026-10-21T11:30:00Z');
  const b = built(now);
  const li = b.campaigns.filter((c) => c.status === 'posted' && c.platforms.includes('linkedin'));
  assert.ok(li.length >= 5 && li.some((c) => now - c.publishedAt < 30 * DAY));
  for (const c of b.campaigns.filter((x) => x.status === 'posted')) {
    for (const p of c.publishResult.postIds) assert.match(p.postUrl, /^https:\/\/[^\s]{4,300}$/);
  }
  const row = new (model('Campaign'))(b.campaigns.find((c) => c.status === 'posted'));
  assert.ok(String(row.publishResult.postIds[0].postUrl || '').startsWith('https://'), 'the link survives the Campaign model');
});

test('every reel points at a TALL clip; the products without a studio video get a reel-only clip', () => {
  const urls = videos.videoUrlsOf(BASE);
  assert.strictEqual(Object.keys(urls).length, K.PRODUCTS.length, 'every product has a clip for its reels');
  const wide = videos.VIDEOS.filter((v) => v.wide).map((v) => videos.mp4Rel(v));
  assert.ok(Object.values(urls).every((u) => !wide.some((w) => u.endsWith(w))), 'no reel uses the wide studio video');
  assert.ok(videos.REELS.every((v) => v.reel && /^videos\/reel-[a-z0-9-]+\.mp4$/.test(videos.mp4Rel(v)) && videos.posterRel(v).endsWith('.jpg') && !v.wide));
  const b = built(new Date('2026-10-21T11:30:00Z'));
  assert.ok(b.drafts.filter((d) => d.contentType === 'reel').every((d) => d.creative && d.creative.videoUrl.endsWith('.mp4')), 'no reel is left without a video');
});

test('saved ideas, bell notifications and the business context are valid rows of the real models', () => {
  const now = new Date('2026-10-21T11:30:00Z');
  const ideas = extras.ideaRows({ userId: UID, now });
  assert.strictEqual(ideas.length, 7);
  for (const r of ideas) assert.strictEqual(new (model('ContentIdea'))(r).validateSync(), undefined);
  const b = built(now);
  const notes = extras.notificationRows({ userId: UID, campaigns: b.campaigns, now });
  assert.strictEqual(notes.length, 4);
  for (const r of notes) {
    assert.strictEqual(new (model('Notification'))(r).validateSync(), undefined);
    assert.ok(now - r.createdAt < 24 * 3600000, 'inside the 24 hours the bell lists');
  }
  assert.ok(notes.some((n) => n.readAt === null));
  const ctx = new (model('OnboardingContext'))(extras.onboardingContextRow({ userId: UID }));
  assert.strictEqual(ctx.validateSync(), undefined);
});

test('the older Competitor Activity Feed has posts with pictures, and the auto-reply tone is one the page offers', () => {
  const now = new Date('2026-10-21T11:30:00Z');
  const comp = competitors.build({ userId: UID, now, base: BASE });
  assert.ok(comp.competitors.every((c) => c.posts.length >= 1 && c.posts.every((p) => p.imageUrl.startsWith(BASE) && /^https:\/\/www\.instagram\.com\//.test(p.postUrl) && now - p.postedAt < 30 * DAY)), JSON.stringify(comp.competitors.map((c) => c.posts.length)));
  for (const c of comp.competitors) assert.strictEqual(new (model('Competitor'))(c).validateSync(), undefined);
  const settings = inbox.settingsRow(UID, now);
  assert.ok(['professional', 'friendly', 'luxury', 'playful', 'supportive'].includes(settings.businessTone));
});

test('Home\'s "Today\'s plan" has a row at any hour: a post later today, or (after 8 pm) one posted this morning', () => {
  const day = istWeek(new Date('2026-10-21T11:30:00Z'));
  const early = new Date('2026-10-21T04:30:00Z'); // 10:00 India time
  const be = built(early);
  assert.ok(be.campaigns.some((c) => c.status === 'scheduled' && c.scheduledFor > early && c.scheduledFor - early < DAY), 'one is scheduled later the same day');
  const late = new Date('2026-10-21T17:00:00Z'); // 22:30 India time
  const bl = built(late);
  const todayStart = new Date('2026-10-20T18:30:00Z'); // 00:00 on the 21st in India
  assert.ok(bl.campaigns.some((c) => c.status === 'posted' && c.publishedAt >= todayStart && c.publishedAt < late), 'one was posted this morning');
  assert.ok(day.startsAt <= todayStart);
  for (const b of [be, bl]) assert.deepStrictEqual(b.summary, { needsApproval: 8, drafts: 4, approved: 4, scheduled: 10, posted: 55, archived: 6, binned: 3 });
});
