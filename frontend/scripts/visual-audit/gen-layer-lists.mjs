#!/usr/bin/env node
// Generates the LIGHT SEMANTICS part of the GRAVITY OVERRIDE LAYER in frontend/index.html
// (between the "LIGHT SEMANTICS" begin/end markers).
//
//   node scripts/visual-audit/gen-layer-lists.mjs           # rewrite the block in index.html
//   node scripts/visual-audit/gen-layer-lists.mjs --check   # exit 1 if index.html is out of date
//
// Why generated: the dark-era Tailwind classes the pages still carry (text-white, bg-slate-900,
// bg-white/5, text-[#ffcc29], bg-[#0A66C2] ...) need many selectors, and several of them must
// share ONE definition of "dark surface" and "saturated fill". Every list below is defined once
// here and expanded into the CSS. Selector lists keep only class names the frontend source uses
// (scanned on every run), so the CSS stays small; re-run the script after adding pages.
//
// Extending: add a class to the right list below (DARK, FILL_*, LIGHT, GOLD, LEGACY_*, text
// tiers, PALE ...) and re-run. New code should not need this layer at all: use the --gv-* tokens
// (text-[var(--gv-text-primary)], bg-[var(--gv-panel)], border-[var(--gv-border-subtle)]).
// An intentionally dark panel that is not caught by a class can carry data-nb-surface="dark".
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, '../..');
const INDEX = join(frontend, 'index.html');
const BEGIN = '      /* ---- begin LIGHT SEMANTICS (generated by scripts/visual-audit/gen-layer-lists.mjs; do not edit by hand) ---- */\n';
const END = '      /* ---- end LIGHT SEMANTICS ---- */\n';

// ---- source scan --------------------------------------------------------------------------------
const SKIP = /(^|\/)(node_modules|dist|scripts|tests|public)(\/|$)/;
function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    const rel = relative(frontend, p);
    if (SKIP.test(rel)) continue;
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (/\.(tsx|ts|jsx|js)$/.test(f)) out.push(p);
  }
  return out;
}
const SRC = walk(frontend).sort().map((p) => readFileSync(p, 'utf8')).join('\n');
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const usedCache = new Map();
// A class (or class prefix) counts as used when it starts a class token somewhere in the source.
const used = (c) => {
  if (!usedCache.has(c)) usedCache.set(c, new RegExp('(^|[\\s"\'`{:])' + esc(c)).test(SRC));
  return usedCache.get(c);
};

// ---- selector helpers -----------------------------------------------------------------------------
const S = 'body.gravity-shell';
// Exact class token, or a prefix of one (text-white matches text-white/55): at the start of the
// attribute or after a space, so variants such as dark:text-white or hover:bg-white/5 never match.
const A = (c) => `[class^="${c}"],[class*=" ${c}"]`;
const X = (c) => `[class~="${c}"]`; // exact token only
const list = (classes, fn = A) => classes.filter(used).map(fn);
const is = (sels) => `:is(${sels.join(',')})`;
const where = (sels) => `:where(${sels.join(',')})`;
const out = [];
const wrap = (s, n = 110) => {
  const parts = s.split(/,(?=(?:[^"]*"[^"]*")*[^"]*$)/);
  const lines = []; let cur = '';
  for (const p of parts) { if (cur && (cur + ',' + p).length > n) { lines.push(cur + ','); cur = p; } else cur = cur ? cur + ',' + p : p; }
  lines.push(cur); return lines.join('\n        ');
};
const rule = (sel, body) => { if (/:(is|where)\(\)/.test(sel)) return; out.push(`      ${wrap(sel)} {\n        ${body.join('\n        ')}\n      }`); };
const note = (...l) => out.push(`      /* ${l.join('\n         ')} */`);

// ---- colour maths (for arbitrary hex fills) ------------------------------------------------------
const lin = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
const lum = (hex) => { let h = hex.replace('#', ''); if (h.length === 3) h = [...h].map((c) => c + c).join(''); const n = (i) => parseInt(h.slice(i, i + 2), 16); return 0.2126 * lin(n(0)) + 0.7152 * lin(n(2)) + 0.0722 * lin(n(4)); };
const whiteRatio = (hex) => 1.05 / (lum(hex) + 0.05);
const inkRatio = (hex) => (lum(hex) + 0.05) / (lum('#1A1208') + 0.05);

// ---- the lists (defined once) ---------------------------------------------------------------------
const HUES = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'];
const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
// Legacy dark backgrounds the layer paints light (page / panel / panel-2).
const LEGACY_PAGE = ['bg-[#070A12]', 'bg-[#0A0A0A]', 'bg-slate-950', 'bg-gray-950', 'bg-[#060810]'];
const LEGACY_PANEL = ['bg-[#0d1117]', 'bg-[#0D1117]', 'bg-[#0f1419]', 'bg-[#151515]', 'bg-[#161b22]', 'bg-[#111111]', 'bg-[#111827]', 'bg-slate-900', 'bg-gray-900', 'bg-slate-800', 'bg-gray-800', 'bg-[#1f2937]', 'bg-[#131920]'];
const LEGACY_PANEL2 = ['bg-[#21262d]', 'bg-[#1A1A1A]', 'bg-slate-700', 'bg-gray-700'];
const LEGACY = [...LEGACY_PAGE, ...LEGACY_PANEL, ...LEGACY_PANEL2];
const LEGACY_HEX = new Set(LEGACY.filter((c) => c.startsWith('bg-[#')).map((c) => c.slice(4, -1).toLowerCase()));
// Black scrims: /50 and more on an element that carries white text (media buttons over images).
const SCRIM_ALPHAS = ['5', '6', '7', '8', '9']; // prefixes: /50 ... /95
// Intentionally dark surfaces: media frames, positioned scrims, lightboxes (/85+), dark banners,
// the image placeholder, explicit markers. Their text stays light, their own fills and fields stay
// dark, and legacy-dark panels inside them are NOT painted light.
const DARK = [
  '[data-nb-surface="dark"]', X('bg-black'),
  `.absolute${is([A('bg-black/')])}`,
  `.fixed${is([...A('bg-black/85').split(','), ...A('bg-black/9').split(',')])}`,
  `${is(SCRIM_ALPHAS.flatMap((a) => A(`bg-black/${a}`).split(',')))}${is(A('text-white').split(','))}`,
  ...list(['from-black', 'bg-[#141414]']), '.igCanvas',
];
const DARK_SEL = DARK.join(',');
// Excludes descendants of a dark surface and an element explicitly marked dark. (Elements that are
// themselves a dark class - bg-black, scrims - are never targeted by the light remaps.)
const NOT_IN_DARK = `:not(:is(${DARK_SEL}) *):not([data-nb-surface="dark"])`;
// Arbitrary-hex fills used in the source, classified by luminance.
const hexes = new Set();
for (const m of SRC.matchAll(/(?:^|[\s"'`{])((?:bg|from)-\[#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\])(?!\/)/g)) hexes.add(m[1]);
// Brand fills are always listed (whether or not a page uses them yet) and classified like the rest:
// #1DA1F2 is too light for white (2.84:1), so it gets dark ink.
const BRAND = ['bg-[#1877F2]', 'bg-[#0A66C2]', 'bg-[#BD081C]', 'bg-[#FF0000]', 'bg-[#FF4500]', 'bg-[#1DA1F2]', 'bg-[#E60023]', 'bg-[#25D366]'];
const GOLD_HEX = ['bg-[#ffcc29]', 'bg-[#F5A623]', 'bg-[#f5a623]', 'bg-[#e6b825]', 'bg-[#ffb833]', 'bg-[#ffd84f]', 'bg-[#ebd038]', 'bg-[#e6b800]', 'bg-[#f5c200]', 'from-[#ffcc29]', 'from-[#F5A623]'];
const hexOf = (c) => c.slice(c.indexOf('#'), -1);
for (const b of BRAND) hexes.add(b);
const HEX_FILL = [], HEX_MID = [], HEX_LIGHT = [];
for (const c of [...hexes].sort()) {
  const h = hexOf(c);
  if (GOLD_HEX.includes(c) || (c.startsWith('bg-') && LEGACY_HEX.has(h.toLowerCase()))) continue;
  if (whiteRatio(h) >= 3) HEX_FILL.push(c); // white text on it reaches 3:1: a saturated/dark fill
  else if (lum(h) > 0.6) HEX_LIGHT.push(c);
  else if (inkRatio(h) >= 4.5) HEX_MID.push(c); // mid-light fill: dark ink reads, white does not
}
const FILL = [
  ...list(HUES.filter((h) => h !== 'yellow' && h !== 'amber').flatMap((h) => [400, 500, 600, 700, 800, 900].flatMap((n) => [`bg-${h}-${n}`, `from-${h}-${n}`]))),
  ...list(['amber', 'yellow'].flatMap((h) => [600, 700, 800, 900].flatMap((n) => [`bg-${h}-${n}`, `from-${h}-${n}`]))),
  ...list(NEUTRALS.flatMap((h) => [400, 500, 600].flatMap((n) => [`bg-${h}-${n}`, `from-${h}-${n}`]))),
  ...HEX_FILL.map(A).flatMap((x) => x.split(',')), ...list(['bg-[var(--gv-coral)]']),
  // Inline-style fills (React writes them as rgb()): the element's own fill keeps light text.
  // (static markup keeps the hex as written, so both forms are listed).
  ...['background-color: rgb(', 'background: rgb(', 'background-color: #', 'background-color:#', 'background: #', 'background:#'].map((v) => `[style*="${v}"]`),
];
// Inline-style fills that are too light for white (white < 3:1): every quoted hex literal in the
// source (e.g. Analytics metric colours '#ffcc29') is classified; React writes it as rgb(r, g, b).
const INLINE_INK = [];
for (const m of SRC.matchAll(/["'`]\s*(#[0-9a-fA-F]{6}|#[0-9a-fA-F]{3})\b["'`]/g)) {
  const h = m[1].toLowerCase();
  if (whiteRatio(h) >= 3) continue;
  let x = h.slice(1); if (x.length === 3) x = [...x].map((c) => c + c).join('');
  const rgb = `rgb(${parseInt(x.slice(0, 2), 16)}, ${parseInt(x.slice(2, 4), 16)}, ${parseInt(x.slice(4, 6), 16)})`;
  for (const sel of [`[style*="background-color: ${rgb}"]`, `[style*="background: ${rgb}"]`, `[style*="background-color: ${h}" i]`, `[style*="background: ${h}" i]`]) if (!INLINE_INK.includes(sel)) INLINE_INK.push(sel);
}
// Multi-stop saturated gradients (e.g. Instagram: from-yellow-400 via-red-500 to-purple-600):
// listed after GOLD so a yellow first stop does not turn the white icon dark.
const FILL_MULTI = list(HUES.filter((h) => h !== 'yellow' && h !== 'amber').flatMap((h) => [500, 600, 700].flatMap((n) => [`via-${h}-${n}`, `to-${h}-${n}`])));
const LIGHT = [
  ...['bg-white', 'bg-slate-50', 'bg-gray-50', 'bg-slate-100', 'bg-gray-100', 'bg-[#f5f5f5]'].filter(used).map(X),
  ...list(['bg-[var(--gv-panel)]', 'bg-[var(--gv-panel-2)]', 'bg-[var(--gv-bg)]', ...HEX_LIGHT]),
  '[style*="var(--gv-panel)"]', '[style*="background-color: rgb(255, 255, 255)"]', '[style*="background: rgb(255, 255, 255)"]',
  '[style*="background-color: rgba("]', '[style*="background: rgba("]',
  ...['#fff;', '#fff"', '#ffffff', '#FFF;', '#FFFFFF', 'white'].flatMap((v) => [`[style*="background-color: ${v}"]`, `[style*="background: ${v}"]`]),
  // legacy dark panels that the layer paints light (when they are not inside a dark surface)
  `${is(list(LEGACY))}${NOT_IN_DARK}`,
];
const GOLD = [...HEX_MID.map(A).flatMap((x) => x.split(',')), ...list([...GOLD_HEX, 'bg-[var(--gv-accent)]', ...['amber', 'yellow'].flatMap((h) => [300, 400, 500].flatMap((n) => [`bg-${h}-${n}`, `from-${h}-${n}`]))])];
const TINT = list([
  ...HUES.flatMap((h) => [400, 500, 600, 700, 800, 900].flatMap((n) => [`bg-${h}-${n}/`, `from-${h}-${n}/`])),
  ...NEUTRALS.flatMap((h) => [400, 500, 600].flatMap((n) => [`bg-${h}-${n}/`, `from-${h}-${n}/`])),
  ...[...HEX_FILL, ...GOLD_HEX, ...HEX_MID].map((c) => c + '/'),
]);
const PALE = { green: ['#166534', '#86EFAC'], emerald: ['#065F46', '#6EE7B7'], teal: ['#115E59', '#5EEAD4'], cyan: ['#155E75', '#67E8F9'], sky: ['#075985', '#7DD3FC'], blue: ['#1D4ED8', '#93C5FD'], indigo: ['#4338CA', '#A5B4FC'], violet: ['#6D28D9', '#C4B5FD'], purple: ['#7E22CE', '#D8B4FE'], fuchsia: ['#A21CAF', '#F0ABFC'], pink: ['#BE185D', '#F9A8D4'], rose: ['#BE123C', '#FDA4AF'], red: ['#B91C1C', '#FCA5A5'], orange: ['#9A3412', '#FDBA74'], lime: ['#3F6212', '#BEF264'] };
const WEAK600 = new Set(['green', 'emerald', 'teal', 'cyan', 'sky', 'orange', 'lime']);
const FIELDS = ['input[type="text"]', 'input[type="email"]', 'input[type="password"]', 'input[type="url"]', 'input[type="search"]', 'input[type="number"]', 'input[type="date"]', 'input[type="time"]', 'input[type="tel"]', 'input:not([type])', 'textarea', 'select'];
const hoverOf = (prefix, classes) => classes.filter((c) => used(`${prefix}:${c}`)).flatMap((c) => [`[class^="${prefix}:${c}"]`, `[class*=" ${prefix}:${c}"]`]);

const NF = ':not(input):not(textarea):not(select)'; // form fields take the field rules

// ---- 1. surface context ---------------------------------------------------------------------------
note('1. Surface context. Dark-era text classes read their colour from these variables, inherited,',
  'so the nearest surface wins: ink on the page and light panels; light on saturated fills and',
  'intentionally dark surfaces; dark ink on gold. All four rules have equal specificity (:where),',
  'so source order decides (tints after fills, light panels after dark surfaces).');
const ctx = (t1, t2, t3, acc, pale) => [`--nb-t1: ${t1};`, `--nb-t2: ${t2};`, `--nb-t3: ${t3};`, `--nb-acc: ${acc};`, ...Object.entries(PALE).map(([h, v]) => `--nb-${h}: ${v[pale]};`)];
const lightCtx = ctx('var(--gv-text-primary)', 'var(--gv-text-secondary)', 'var(--gv-text-tertiary)', 'var(--gv-accent-text)', 0);
const darkCtx = ctx('#FFFFFF', 'rgb(255 255 255 / 0.88)', 'rgb(255 255 255 / 0.78)', '#F5A623', 1);
const goldCtx = ctx('var(--gv-accent-ink)', 'rgb(26 18 8 / 0.88)', 'rgb(26 18 8 / 0.80)', 'var(--gv-accent-ink)', 0);
rule(S, lightCtx);
rule(`${S} ${where([...FILL, ...DARK])}`, darkCtx);
rule(`${S} ${where(LIGHT)}`, lightCtx);
rule(`${S} ${where([...GOLD, ...INLINE_INK])}`, goldCtx);
rule(`${S} ${where(FILL_MULTI)}`, darkCtx);
rule(`${S} ${where(TINT)}`, lightCtx);
// a dark surface nested in a light panel inside a dark area still wins over the reset
rule(`${S} ${where(['[data-nb-surface="dark"]'])}`, darkCtx);

// ---- 2. text ---------------------------------------------------------------------------------------
note('2. Text tiers: /80 and up -> primary, /60-/75 and slate/gray-300 -> secondary, the rest -> tertiary.');
const LIGHTTEXT = ['text-white', 'text-[#ededed]', 'text-[#EDEDED]', 'text-[#F5F4F1]', 'text-[#f5f4f1]'];
rule(`${S} ${is(list([...LIGHTTEXT, 'text-slate-100', 'text-slate-200', 'text-gray-100', 'text-gray-200', 'text-[rgba(245,244,241']))}`, ['color: var(--nb-t1) !important;']);
rule(`${S} ${is(list(LIGHTTEXT.flatMap((c) => ['/60', '/65', '/70', '/75', '/[0.6', '/[0.7'].map((a) => c + a)).concat(['text-slate-300', 'text-gray-300', 'text-[rgba(245,244,241,0.6', 'text-[rgba(245,244,241,0.7'])))}`, ['color: var(--nb-t2) !important;']);
rule(`${S} ${is(list(LIGHTTEXT.flatMap((c) => ['/5', '/4', '/3', '/2', '/1', '/[0.5', '/[0.4', '/[0.3', '/[0.2', '/[0.1', '/[0.0'].map((a) => c + a)).concat(['text-slate-400', 'text-slate-500', 'text-slate-600', 'text-gray-400', 'text-gray-500', 'text-gray-600', 'text-[rgba(245,244,241,0.5', 'text-[rgba(245,244,241,0.4', 'text-[rgba(245,244,241,0.3', 'text-[rgba(255,255,255,0.'])))}`, ['color: var(--nb-t3) !important;']);
rule(`${S} ${is(hoverOf('hover', ['text-white', 'text-[#F5F4F1]', 'text-[#ededed]']))}:hover`, ['color: var(--nb-t1) !important;']);

// ---- 3. backgrounds --------------------------------------------------------------------------------
note('3. Legacy dark backgrounds become the light page / panel tokens, except on or inside an',
  'intentionally dark surface (a dark panel in a lightbox stays dark, with its light text).');
rule(`${S} ${is(list(LEGACY_PAGE))}${NOT_IN_DARK}`, ['background-color: var(--gv-bg) !important;']);
rule(`${S} ${is(list(LEGACY_PANEL))}${NOT_IN_DARK}`, ['background-color: var(--gv-panel) !important;']);
rule(`${S} ${is(list(LEGACY_PANEL2))}${NOT_IN_DARK}`, ['background-color: var(--gv-panel-2) !important;']);
note('Translucent black boxes become an ink tint; scrims (positioned, lightboxes, /50+ under white text) stay dark.');
rule(`${S} ${is(A('bg-black/').split(','))}:not(.absolute):not(.fixed):not(${DARK[4]})${NOT_IN_DARK}`, ['background-color: var(--gv-surface-2) !important;']);

// ---- 4. white-alpha surfaces and borders --------------------------------------------------------------
note('4. White-alpha surfaces and borders become ink tints and cream rules (not on dark surfaces,',
  'not on form fields). hover:/focus: variants too, so the feedback is visible on cream.');
rule(`${S} ${is(A('bg-white/').split(','))}${NOT_IN_DARK}${NF}`, ['background-color: var(--gv-surface-2) !important;']);
rule(`${S} ${is(list(['bg-white/[0.0', 'bg-white/5', 'bg-white/[0.02', 'bg-white/[0.03']))}${NOT_IN_DARK}${NF}`, ['background-color: var(--gv-surface-1) !important;']);
rule(`${S} ${is(list(['bg-white/10', 'bg-white/[0.1']))}${NOT_IN_DARK}${NF}`, ['background-color: var(--gv-surface-3) !important;']);
rule(`${S} ${is(list(['bg-white/2', 'bg-white/3', 'bg-white/[0.2', 'bg-white/[0.3']))}${NOT_IN_DARK}${NF}`, ['background-color: var(--gv-surface-4) !important;']);
rule(`${S} ${is(A('border-white/').split(','))}${NOT_IN_DARK}${NF}`, ['border-color: var(--gv-border-subtle) !important;']);
rule(`${S} ${is(list(['border-white/1', 'border-white/2', 'border-white/3', 'border-white/[0.1', 'border-white/[0.2', 'border-white/[0.3']))}${NOT_IN_DARK}${NF}`, ['border-color: var(--gv-border-default) !important;']);
rule(`${S} ${is(hoverOf('hover', ['bg-white/']))}${NOT_IN_DARK}${NF}:hover`, ['background-color: var(--gv-surface-3) !important;']);
rule(`${S} ${is(hoverOf('focus', ['bg-white/']))}${NOT_IN_DARK}${NF}:focus`, ['background-color: var(--gv-surface-3) !important;']);
rule(`${S} ${is([...hoverOf('hover', ['border-white/'])])}${NOT_IN_DARK}:hover`, ['border-color: var(--gv-border-strong) !important;']);
rule(`${S} ${is([...hoverOf('focus', ['border-white/'])])}${NOT_IN_DARK}:focus`, ['border-color: var(--gv-accent-text) !important;']);
note('Dark-era slate/gray-700/800 borders and dividers become cream rules.');
rule(`${S} ${is(list(['border-slate-700', 'border-slate-800', 'border-gray-700', 'border-gray-800']))}${NOT_IN_DARK}${NF}`, ['border-color: var(--gv-border-subtle) !important;']);
rule(`${S} ${is(list(['divide-slate-700', 'divide-slate-800', 'divide-gray-700']))}${NOT_IN_DARK} > *`, ['border-color: var(--gv-border-subtle) !important;']);

// ---- 5. form fields -----------------------------------------------------------------------------------
note('5. Fields: panel fill, ink text, a 1px border in --gv-text-muted (3.4:1, the 3:1 rule for UI',
  'component borders), tertiary placeholders (5.9:1), focus = accent-text border + 25% accent ring.',
  '.gravity-bare fields (inside a GravityPanel, which draws the box) and border-0 fields are left alone.');
const fieldSel = FIELDS.map((f) => `${S} ${f}`).join(',');
rule(fieldSel, ['background-color: var(--gv-panel) !important;', 'color: var(--gv-text-primary) !important;', 'border-color: var(--gv-text-muted) !important;']);
rule(FIELDS.map((f) => `${S} ${f}:not(.gravity-bare):not(.border-0):not(.border-none)`).join(','), ['border-width: 1px;', 'border-style: solid;']);
rule(`${S} input::placeholder,${S} textarea::placeholder`, ['color: var(--gv-text-tertiary) !important;', 'opacity: 1 !important;']);
rule(`${S} :is(input, textarea, select):focus`, ['border-color: var(--gv-accent-text) !important;', 'outline: none !important;', 'box-shadow: 0 0 0 3px rgb(var(--gv-accent-rgb) / 0.25) !important;']);
note('Fields on an intentionally dark surface keep the dark styling.');
rule(`${S} ${where(DARK)} :is(${FIELDS.join(', ')})`, ['background-color: rgb(255 255 255 / 0.04) !important;', 'border-color: rgb(255 255 255 / 0.30) !important;', 'color: #F5F4F1 !important;']);
rule(`${S} ${where(DARK)} :is(input, textarea)::placeholder`, ['color: rgb(255 255 255 / 0.60) !important;']);
note('Opt-out for fields inside a GravityPanel: the panel already draws the surface.');
rule(`${S} textarea.gravity-bare,${S} input.gravity-bare,${S} textarea.gravity-bare:focus,${S} input.gravity-bare:focus`, ['background-color: transparent !important;', 'border: none !important;', 'box-shadow: none !important;', 'outline: none !important;']);

// ---- 6. gold ------------------------------------------------------------------------------------------
note('6. Legacy yellow fills -> Gravity gold with dark ink (solid fills only; tints such as',
  'bg-[#ffcc29]/10 stay light). Gold/yellow TEXT -> the AA-safe accent text colour.');
const GOLDFILL = `${is(A('bg-[#ffcc29]').split(','))}:not([class^="bg-[#ffcc29]/"]):not([class*=" bg-[#ffcc29]/"])`;
rule(`${S} ${GOLDFILL}:not(aside)`, ['background-color: var(--grav-gold) !important;', 'color: var(--gv-accent-ink) !important;']);
rule(`${S} :is(button, a)${GOLDFILL}`, ['box-shadow: 0 4px 18px rgba(245,166,35,0.20) !important;']);
rule(`${S} :is(button, a)${GOLDFILL}:hover`, ['background-color: var(--grav-gold-hover) !important;']);
rule(`${S} ${is(A('border-[#ffcc29]').split(','))}`, ['border-color: var(--grav-gold) !important;']);
